import pytest

from leetcode_py import logged_test

from .helpers import assert_number_of_beams, run_number_of_beams
from .solution import Solution


class TestNumberOfLaserBeamsInABank:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "bank, expected",
        [
            (["011001", "000000", "010100", "001000"], 8),
            (["000", "111", "000"], 0),
            (["0"], 0),
            (["1"], 0),
            (["0", "1"], 0),
            (["1", "1"], 1),
            (["11", "11"], 4),
            (["101", "000", "101"], 4),
            (["10", "00", "01", "00", "10"], 2),
            (["1", "0", "1", "0", "1"], 2),
            (["0110", "0000", "1001", "0000", "1111"], 12),
            (["0000"], 0),
            (["1", "1", "1", "1"], 3),
            (["111", "000", "000", "111"], 9),
            (["0101", "1010", "0101"], 8),
            (["1000", "1100", "1110", "1111"], 20),
            (["00100", "00000", "01000", "00000", "10000"], 2),
            (["000000000000", "111111111111", "000000000000", "111111111111"], 144),
            (["1", "0", "0"], 0),
            (["001", "101", "011", "000", "111", "011"], 18),
            (["010110", "101101", "011101"], 28),
            (["110001"], 0),
            (["11010000"], 0),
            (["01011"], 0),
            (["0", "1", "0", "1"], 1),
            (["00", "11", "00", "00"], 0),
            (["110", "011", "000", "000", "000"], 4),
            (["01", "01", "01", "11", "00", "10"], 6),
            (["1000001", "1011100", "1011110", "1110101"], 53),
            (["11"], 0),
            (["0001111", "1101000"], 12),
            (["0111101", "0111001", "0010111", "1011110", "1111010", "1100011"], 101),
        ],
    )
    def test_number_of_beams(self, bank: list[str], expected: int):
        result = run_number_of_beams(Solution, bank)
        assert_number_of_beams(result, expected)
