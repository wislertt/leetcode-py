import pytest

from leetcode_py import logged_test

from .helpers import assert_super_palindromes_in_range, run_super_palindromes_in_range
from .solution import Solution


class TestSuperPalindromes:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "left, right, expected",
        [
            ("4", "1000", 4),
            ("1", "2", 1),
            ("1", "1", 1),
            ("2", "2", 0),
            ("3", "3", 0),
            ("4", "4", 1),
            ("9", "9", 1),
            ("10", "10", 0),
            ("11", "11", 0),
            ("121", "121", 1),
            ("676", "676", 0),
            ("1", "9", 3),
            ("1", "100", 3),
            ("100", "10000", 2),
            ("1000", "1000000", 5),
            ("99999999999999999", "999999999999999999", 0),
            ("384993223391482364", "616150121133157331", 0),
            ("309800857263518530", "984422537336625948", 0),
            ("422703056767326185", "741474729361013312", 0),
            ("458602564538043363", "735449500685093205", 0),
            ("975260454454743092", "989961279379753474", 0),
            ("398780163542857328", "995774918789191964", 0),
            ("43996935910671708", "263225791936751430", 0),
            ("1234320", "1234321", 1),
            ("1234321", "1234322", 1),
            ("10221412200", "10221412201", 1),
            ("10221412201", "10221412202", 1),
            ("1212225222120", "1212225222121", 1),
            ("1212225222121", "1212225222122", 1),
            ("121242363242120", "121242363242121", 1),
            ("121242363242121", "121242363242122", 1),
            ("10203040504030200", "10203040504030201", 1),
            ("10203040504030201", "10203040504030202", 1),
        ],
    )
    def test_super_palindromes_in_range(self, left: str, right: str, expected: int):
        result = run_super_palindromes_in_range(Solution, left, right)
        assert_super_palindromes_in_range(result, expected)
