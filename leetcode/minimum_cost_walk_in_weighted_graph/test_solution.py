import pytest

from leetcode_py import logged_test

from .helpers import assert_minimum_cost, run_minimum_cost
from .solution import Solution


class TestMinimumCostWalkInWeightedGraph:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "n, edges, query, expected",
        [
            (5, [[0, 1, 7], [1, 3, 7], [1, 2, 1]], [[0, 3], [3, 4]], [1, -1]),
            (3, [[0, 2, 7], [0, 1, 15], [1, 2, 6], [1, 2, 1]], [[1, 2]], [0]),
            (2, [[0, 1, 5]], [[0, 1]], [5]),
            (2, [], [[0, 1]], [-1]),
            (4, [[0, 1, 3], [2, 3, 3]], [[0, 1], [0, 2], [2, 3]], [3, -1, 3]),
            (3, [[0, 1, 0]], [[0, 1], [1, 0]], [0, 0]),
            (4, [[0, 1, 1], [1, 2, 2], [2, 3, 4]], [[0, 3], [1, 3], [0, 2]], [0, 0, 0]),
            (5, [[0, 1, 7], [1, 3, 7], [1, 2, 1]], [[4, 3], [0, 1], [2, 3]], [-1, 1, 1]),
            (2, [[0, 1, 4], [0, 1, 3]], [[0, 1]], [0]),
            (4, [[0, 1, 65535], [1, 2, 2]], [[0, 2], [2, 0]], [2, 2]),
            (6, [[0, 1, 8], [2, 3, 8], [4, 5, 8]], [[0, 1], [1, 2], [2, 3], [4, 5]], [8, -1, 8, 8]),
            (4, [[0, 1, 100000], [1, 2, 100000]], [[0, 2], [0, 3]], [100000, -1]),
            (3, [[0, 1, 100000], [1, 2, 0]], [[0, 2]], [0]),
            (4, [[0, 1, 12], [0, 2, 10], [0, 3, 6]], [[1, 2], [1, 3], [2, 3]], [0, 0, 0]),
            (5, [[3, 1, 6], [3, 4, 3]], [[1, 3], [1, 0], [2, 1]], [2, -1, -1]),
            (3, [[0, 1, 7], [2, 0, 6], [1, 0, 0], [2, 1, 5], [2, 1, 1]], [[2, 1], [2, 0]], [0, 0]),
            (2, [], [[0, 1], [1, 0]], [-1, -1]),
            (4, [[2, 0, 12], [0, 1, 0], [2, 1, 100000]], [[0, 2], [2, 1]], [0, 0]),
            (2, [[0, 1, 0], [0, 1, 12], [1, 0, 1]], [[0, 1], [1, 0], [1, 0]], [0, 0, 0]),
            (4, [[0, 3, 8], [0, 1, 5], [1, 2, 8], [0, 1, 100000]], [[0, 1], [2, 1]], [0, 0]),
            (3, [[1, 2, 12], [2, 1, 0], [1, 0, 6], [0, 1, 8]], [[2, 0]], [0]),
            (3, [[0, 1, 0]], [[1, 0], [0, 1], [1, 2]], [0, 0, -1]),
        ],
    )
    def test_minimum_cost(
        self, n: int, edges: list[list[int]], query: list[list[int]], expected: list[int]
    ):
        result = run_minimum_cost(Solution, n, edges, query)
        assert_minimum_cost(result, expected)
