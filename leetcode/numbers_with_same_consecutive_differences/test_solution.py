    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "n, k, expected",
        [
            (3, 7, [181, 292, 707, 818, 929]),
            (2, 1, [10, 12, 21, 23, 32, 34, 43, 45, 54, 56, 65, 67, 76, 78, 87, 89, 98]),
            (2, 0, [11, 22, 33, 44, 55, 66, 77, 88, 99]),
            (3, 0, [111, 222, 333, 444, 555, 666, 777, 888, 999]),
            (4, 0, [1111, 2222, 3333, 4444, 5555, 6666, 7777, 8888, 9999]),
            (5, 0, [11111, 22222, 33333, 44444, 55555, 66666, 77777, 88888, 99999]),
            (2, 2, [13, 20, 24, 31, 35, 42, 46, 53, 57, 64, 68, 75, 79, 86, 97]),
            (2, 3, [14, 25, 30, 36, 41, 47, 52, 58, 63, 69, 74, 85, 96]),
            (2, 4, [15, 26, 37, 40, 48, 51, 59, 62, 73, 84, 95]),
            (2, 5, [16, 27, 38, 49, 50, 61, 72, 83, 94]),
            (2, 6, [17, 28, 39, 60, 71, 82, 93]),
            (2, 7, [18, 29, 70, 81, 92]),
            (2, 8, [19, 80, 91]),
            (2, 9, [90]),
            (5, 9, [90909]),
            (9, 9, [909090909]),
            (9, 8, [191919191, 808080808, 919191919]),
            (9, 7, [181818181, 292929292, 707070707, 818181818, 929292929]),
            (3, 4, [151, 159, 262, 373, 404, 484, 515, 595, 626, 737, 840, 848, 951, 959]),
            (3, 6, [171, 282, 393, 606, 717, 828, 939]),
            (4, 7, [1818, 2929, 7070, 8181, 9292]),
            (8, 6, [17171717, 28282828, 39393939, 60606060, 71717171, 82828282, 93939393]),
            (6, 6, [171717, 282828, 393939, 606060, 717171, 828282, 939393]),
            (7, 6, [1717171, 2828282, 3939393, 6060606, 7171717, 8282828, 9393939]),
        ],
    )
    def test_nums_same_consec_diff(self, n: int, k: int, expected: list[int]):
        result = run_nums_same_consec_diff(Solution, n, k)
        assert_nums_same_consec_diff(result, expected)
