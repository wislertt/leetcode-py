import pytest

from leetcode_py import logged_test

from .helpers import (
    assert_all_paths_source_target,
    assert_all_paths_source_target_count,
    run_all_paths_source_target,
)
from .solution import Solution


class TestAllPathsSourceTarget:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "graph, expected",
        [
            ([[1, 2], [3], [3], []], [[0, 1, 3], [0, 2, 3]]),
            (
                [[4, 3, 1], [3, 2, 4], [3], [4], []],
                [[0, 1, 2, 3, 4], [0, 1, 3, 4], [0, 1, 4], [0, 3, 4], [0, 4]],
            ),
            ([[1], []], [[0, 1]]),
            ([[1, 2], [], []], [[0, 2]]),
            ([[1], [2], [3], []], [[0, 1, 2, 3]]),
            ([[1, 3], [2], [3], []], [[0, 1, 2, 3], [0, 3]]),
            ([[2], [3], [1, 3], []], [[0, 2, 1, 3], [0, 2, 3]]),
            ([[1, 2], [2, 3], [3], []], [[0, 1, 2, 3], [0, 1, 3], [0, 2, 3]]),
            ([[1, 2, 3], [4], [4], [4], []], [[0, 1, 4], [0, 2, 4], [0, 3, 4]]),
            ([[3], [3], [3], []], [[0, 3]]),
            ([[1, 2, 3], [3], [3], []], [[0, 1, 3], [0, 2, 3], [0, 3]]),
            (
                [[1, 2], [3, 4], [3, 4], [5], [5], []],
                [[0, 1, 3, 5], [0, 1, 4, 5], [0, 2, 3, 5], [0, 2, 4, 5]],
            ),
            ([[1, 2], [2, 3], [3], []], [[0, 1, 2, 3], [0, 1, 3], [0, 2, 3]]),
            ([[1, 2], [3], [1, 3], []], [[0, 1, 3], [0, 2, 1, 3], [0, 2, 3]]),
        ],
    )
    def test_all_paths_source_target(self, graph: list[list[int]], expected: list[list[int]]):
        result = run_all_paths_source_target(Solution, graph)
        assert_all_paths_source_target(result, expected)

