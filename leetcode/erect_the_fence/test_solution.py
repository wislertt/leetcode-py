import pytest

from leetcode_py import logged_test

from .helpers import assert_outer_trees, run_outer_trees
from .solution import Solution


class TestErectTheFence:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "trees, expected",
        [
            ([[0, 0]], [[0, 0]]),
            ([[3, 4], [1, 2]], [[1, 2], [3, 4]]),
            ([[0, 0], [1, 1], [2, 2]], [[0, 0], [1, 1], [2, 2]]),
            ([[0, 0], [2, 0], [1, 2]], [[0, 0], [1, 2], [2, 0]]),
            ([[5, 0], [5, 3], [5, 7]], [[5, 0], [5, 3], [5, 7]]),
            ([[0, 0], [4, 4], [4, 0], [2, 2], [0, 4]], [[0, 0], [0, 4], [4, 0], [4, 4]]),
            ([[0, 0], [2, 2], [4, 4], [0, 4]], [[0, 0], [0, 4], [2, 2], [4, 4]]),
            ([[0, 0], [6, 0], [3, 6], [3, 2], [4, 3]], [[0, 0], [3, 6], [6, 0]]),
            ([[0, 0], [1, 1], [2, 2], [3, 3]], [[0, 0], [1, 1], [2, 2], [3, 3]]),
            ([[2, 3], [2, 9], [2, 5], [8, 5]], [[2, 3], [2, 5], [2, 9], [8, 5]]),
            ([[0, 0], [100, 0], [100, 100], [0, 100]], [[0, 0], [0, 100], [100, 0], [100, 100]]),
            ([[0, 0], [1, 0], [2, 0], [3, 2], [0, 3]], [[0, 0], [0, 3], [1, 0], [2, 0], [3, 2]]),
            ([[1, 1], [2, 2], [2, 0], [2, 4], [4, 2]], [[1, 1], [2, 0], [2, 4], [4, 2]]),
            ([[0, 0], [9, 0], [5, 1], [4, 0], [5, 0]], [[0, 0], [4, 0], [5, 0], [5, 1], [9, 0]]),
            ([[1, 0], [15, 18], [13, 5], [12, 6], [8, 10]], [[1, 0], [8, 10], [13, 5], [15, 18]]),
            ([[5, 17], [16, 7], [17, 6], [17, 3], [20, 6]], [[5, 17], [17, 3], [20, 6]]),
            ([[16, 10], [14, 13], [16, 19], [18, 7], [3, 7]], [[3, 7], [16, 19], [18, 7]]),
            ([[16, 4], [5, 20], [10, 3], [20, 12]], [[5, 20], [10, 3], [16, 4], [20, 12]]),
        ],
    )
    def test_outer_trees(self, trees: list[list[int]], expected: list[list[int]]):
        result = run_outer_trees(Solution, trees)
        assert_outer_trees(result, expected)
