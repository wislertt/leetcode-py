import pytest

from leetcode_py import logged_test

from .helpers import assert_count_nodes, run_count_nodes
from .solution import Solution


class TestCountCompleteTreeNodes:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "root_list, expected",
        [
            ([1, 2, 3, 4, 5, 6], 6),
            ([], 0),
            ([1], 1),
            ([0], 1),
            ([5, 3], 2),
            ([1, 2], 2),
            ([10, 10, 10], 3),
            ([50000, 50000, 50000], 3),
            ([0, 0, 0, 0], 4),
            ([1, 2, 3, 4, 5], 5),
            ([7, 6, 5, 4, 3, 2, 1], 7),
            ([9, 8, 7, 6, 5, 4, 3, 2], 8),
            ([10000, 20000, 30000, 40000, 50000, 0], 6),
            ([26, 33], 2),
            ([39, 46, 53], 3),
            ([0, 7, 14, 21], 4),
            ([13, 20, 27, 34, 41], 5),
            ([26, 33, 40, 47, 54, 61], 6),
            ([39, 46, 53, 60, 67, 74, 81], 7),
            ([0, 7, 14, 21, 28, 35, 42, 49], 8),
            ([13, 20, 27, 34, 41, 48, 55, 62, 69], 9),
            ([26, 33, 40, 47, 54, 61, 68, 75, 82, 89], 10),
            ([39, 46, 53, 60, 67, 74, 81, 88, 95, 1, 8], 11),
            ([0, 7, 14, 21, 28, 35, 42, 49, 56, 63, 70, 77], 12),
            ([13, 20, 27, 34, 41, 48, 55, 62, 69, 76, 83, 90, 97], 13),
            ([26, 33, 40, 47, 54, 61, 68, 75, 82, 89, 96, 2, 9, 16], 14),
            ([39, 46, 53, 60, 67, 74, 81, 88, 95, 1, 8, 15, 22, 29, 36], 15),
            ([0, 7, 14, 21, 28, 35, 42, 49, 56, 63, 70, 77, 84, 91, 98, 4], 16),
            ([13, 20, 27, 34, 41, 48, 55, 62, 69, 76, 83, 90, 97, 3, 10, 17, 24], 17),
            ([26, 33, 40, 47, 54, 61, 68, 75, 82, 89, 96, 2, 9, 16, 23, 30, 37, 44], 18),
            ([39, 46, 53, 60, 67, 74, 81, 88, 95, 1, 8, 15, 22, 29, 36, 43, 50, 57, 64], 19),
            ([0, 7, 14, 21, 28, 35, 42, 49, 56, 63, 70, 77, 84, 91, 98, 4, 11, 18, 25, 32], 20),
        ],
    )
    def test_count_nodes(self, root_list: list[int | None], expected: int):
        result = run_count_nodes(Solution, root_list)
        assert_count_nodes(result, expected)
