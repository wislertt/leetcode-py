import pytest

from leetcode_py import logged_test

from .helpers import assert_min_area_rect, run_min_area_rect
from .solution import Solution


class TestMinimumAreaRectangle:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "points, expected",
        [
            ([[1, 1], [1, 3], [3, 1], [3, 3], [2, 2]], 4),
            ([[1, 1], [1, 3], [3, 1], [3, 3], [4, 1], [4, 3]], 2),
            ([[1, 1]], 0),
            ([[1, 1], [1, 2]], 0),
            ([[1, 1], [1, 3], [3, 1]], 0),
            ([[0, 0], [0, 1], [1, 0], [1, 1]], 1),
            ([[0, 0], [0, 4], [2, 0], [2, 4], [5, 0], [5, 4]], 8),
            ([[3, 2], [3, 1], [2, 2], [1, 1], [1, 2], [2, 1]], 1),
            ([[1, 2], [2, 1], [1, 0], [0, 2]], 0),
            ([[0, 0], [1, 1], [2, 2]], 0),
            ([[0, 0], [0, 5], [5, 0], [5, 5], [3, 3]], 25),
            ([[2, 2], [2, 7], [7, 2], [7, 7], [1, 1], [1, 8], [8, 1], [8, 8]], 25),
            ([[0, 0], [0, 1], [1, 1], [1, 0], [2, 0], [2, 1]], 1),
            ([[0, 1], [2, 1], [0, 3], [2, 3], [1, 0], [3, 0], [1, 2], [3, 2]], 4),
            ([[1, 1], [1, 2], [0, 0], [5, 6]], 0),
            ([[5, 2], [6, 0], [2, 6], [4, 5], [5, 4], [2, 4], [2, 3], [1, 0], [4, 0]], 0),
            ([[5, 4], [0, 3], [2, 1], [1, 4]], 0),
            ([[2, 2], [2, 0], [1, 0], [6, 4], [4, 2], [1, 3], [4, 1]], 0),
            ([[5, 3], [1, 5], [2, 2], [2, 0], [5, 6], [1, 6], [1, 3], [2, 1]], 12),
            ([[0, 0], [3, 0], [2, 0], [3, 6]], 0),
        ],
    )
    def test_min_area_rect(self, points: list[list[int]], expected: int):
        result = run_min_area_rect(Solution, points)
        assert_min_area_rect(result, expected)
