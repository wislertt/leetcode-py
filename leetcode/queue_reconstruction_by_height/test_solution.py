import pytest

from leetcode_py import logged_test

from .helpers import assert_reconstruct_queue, run_reconstruct_queue
from .solution import Solution


class TestQueueReconstructionByHeight:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "people, expected",
        [
            (
                [[7, 0], [4, 4], [7, 1], [5, 0], [6, 1], [5, 2]],
                [[5, 0], [7, 0], [5, 2], [6, 1], [4, 4], [7, 1]],
            ),
            (
                [[6, 0], [5, 0], [4, 0], [3, 2], [2, 2], [1, 4]],
                [[4, 0], [5, 0], [2, 2], [3, 2], [1, 4], [6, 0]],
            ),
            ([[9, 0]], [[9, 0]]),
            ([[1000000, 0]], [[1000000, 0]]),
            ([[1, 0], [2, 0]], [[1, 0], [2, 0]]),
            ([[2, 0], [1, 1]], [[2, 0], [1, 1]]),
            ([[5, 0], [5, 1], [5, 2], [5, 3]], [[5, 0], [5, 1], [5, 2], [5, 3]]),
            ([[4, 3], [9, 0], [10, 0], [6, 1], [6, 0]], [[6, 0], [6, 1], [9, 0], [4, 3], [10, 0]]),
            ([[1, 2], [4, 0], [1, 1]], [[4, 0], [1, 1], [1, 2]]),
            (
                [[1, 2], [10, 0], [2, 2], [6, 0], [10, 1], [6, 1]],
                [[6, 0], [6, 1], [1, 2], [2, 2], [10, 0], [10, 1]],
            ),
            ([[8, 0], [4, 1], [3, 2], [0, 4], [2, 3]], [[8, 0], [4, 1], [3, 2], [2, 3], [0, 4]]),
            ([[6, 0], [2, 0], [6, 2], [9, 0], [3, 3]], [[2, 0], [6, 0], [9, 0], [6, 2], [3, 3]]),
            ([[1, 0], [6, 0]], [[1, 0], [6, 0]]),
            ([[1, 2], [7, 0], [3, 0], [4, 1]], [[3, 0], [7, 0], [1, 2], [4, 1]]),
            ([[2, 2], [9, 0], [6, 0]], [[6, 0], [9, 0], [2, 2]]),
            ([[0, 1], [9, 0], [2, 1]], [[9, 0], [0, 1], [2, 1]]),
            ([[0, 1], [9, 0]], [[9, 0], [0, 1]]),
            ([[9, 0], [7, 0]], [[7, 0], [9, 0]]),
            ([[1000000, 0], [0, 1], [5, 1]], [[1000000, 0], [0, 1], [5, 1]]),
        ],
    )
    def test_reconstruct_queue(self, people: list[list[int]], expected: list[list[int]]):
        result = run_reconstruct_queue(Solution, people)
        assert_reconstruct_queue(result, expected)
