import pytest

from leetcode_py import logged_test

from .helpers import assert_tuple_same_product, run_tuple_same_product
from .solution import Solution


class TestTupleWithSameProduct:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "nums, expected",
        [
            ([2, 3, 4, 6], 8),
            ([1, 2, 4, 5, 10], 16),
            ([2, 3, 5, 7], 0),
            ([1, 2, 3, 4], 0),
            ([1, 2, 6, 3], 8),
            ([2, 4, 8, 16], 8),
            ([1, 3, 9, 27], 8),
            ([3, 1, 4, 2, 8, 6], 32),
            ([1, 2, 3, 4, 6, 12], 40),
            ([1, 5, 10, 2, 4, 20, 8], 72),
            ([86, 107, 72, 187, 113], 0),
            ([60, 56, 101, 121, 156, 193, 65], 0),
            ([137, 45, 158, 94, 127, 160, 198], 0),
            ([107, 177, 99, 86, 12, 131, 4, 195], 0),
            ([125, 50, 81, 83, 1, 43], 0),
            ([177, 82, 114, 31, 56, 87, 19, 167], 0),
            ([1, 2, 3, 4, 5, 6], 16),
            ([2, 4, 6, 8, 12], 16),
            ([3, 4, 6, 8, 12], 16),
            ([1, 2, 4, 8, 16, 32], 56),
            ([2, 3, 4, 6, 8, 12, 24], 72),
            ([1, 2, 3, 6], 8),
            ([4, 6, 8, 12, 16, 24], 40),
            ([1, 2, 5, 10, 20, 50], 32),
            ([6, 8, 12, 16, 24, 48], 32),
            ([2, 6, 3, 9, 18, 27], 40),
            ([1, 3, 5, 15, 30, 45], 16),
            ([10, 15, 20, 30, 60], 16),
            ([5, 10, 15, 30, 60, 90], 32),
            ([12, 18, 24, 36, 72], 16),
            ([24, 8, 32, 16, 48, 56], 16),
            ([28, 30, 90, 60, 21, 20], 8),
            ([35, 28, 80, 20, 12, 48, 18], 8),
            ([40, 54, 50, 20, 44, 10, 108], 16),
            ([120, 30, 84, 10, 55, 16, 64], 8),
            ([45, 144, 24, 20, 22, 54, 21], 8),
        ],
    )
    def test_tuple_same_product(self, nums: list[int], expected: int):
        result = run_tuple_same_product(Solution, nums)
        assert_tuple_same_product(result, expected)
