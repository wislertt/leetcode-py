import pytest

from leetcode_py import logged_test

from .helpers import assert_remove_interval, run_remove_interval
from .solution import Solution


class TestRemoveInterval:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "intervals, to_be_removed, expected",
        [
            ([[0, 2], [3, 4], [5, 7]], [1, 6], [[0, 1], [6, 7]]),
            ([[0, 5]], [2, 3], [[0, 2], [3, 5]]),
            ([[1, 2]], [1, 2], []),
            ([[1, 3], [5, 7]], [3, 5], [[1, 3], [5, 7]]),
            ([[0, 10]], [0, 10], []),
            ([[1, 2], [2, 3], [3, 4]], [2, 3], [[1, 2], [3, 4]]),
            ([[0, 1000000000]], [999999999, 1000000000], [[0, 999999999]]),
            ([[-1000000000, 1000000000]], [-5, 5], [[-1000000000, -5], [5, 1000000000]]),
            ([[1, 2]], [5, 6], [[1, 2]]),
            ([[5, 6]], [1, 2], [[5, 6]]),
            ([[1, 4], [6, 8], [10, 12]], [2, 11], [[1, 2], [11, 12]]),
            ([[1, 3]], [3, 4], [[1, 3]]),
            ([[-3, -1], [0, 2], [4, 6]], [-1, 4], [[-3, -1], [4, 6]]),
            ([[-2, -1], [0, 3], [5, 7]], [-1, 5], [[-2, -1], [5, 7]]),
            (
                [[-4, -2], [0, 1], [3, 6], [8, 9], [11, 14]],
                [1, 8],
                [[-4, -2], [0, 1], [8, 9], [11, 14]],
            ),
            ([[-6, -4], [-2, 0], [2, 4]], [-5, 3], [[-6, -5], [3, 4]]),
            ([[-30, -19], [3, 7]], [-6, 19], [[-30, -19]]),
            ([[-29, -3], [15, 29]], [-32, 28], [[28, 29]]),
            ([[-17, -13], [10, 11]], [-8, -4], [[-17, -13], [10, 11]]),
            ([[-29, -5]], [-28, -15], [[-29, -28], [-15, -5]]),
            ([[-19, 25]], [-11, -2], [[-19, -11], [-2, 25]]),
            ([[-29, -6]], [-12, 26], [[-29, -12]]),
            ([[-23, -21], [-18, -15], [11, 16], [22, 25]], [-24, 19], [[22, 25]]),
            (
                [[-27, -22], [-15, -4], [2, 15], [19, 27]],
                [1, 22],
                [[-27, -22], [-15, -4], [22, 27]],
            ),
            (
                [[-20, -17], [-16, 0], [19, 23], [26, 29]],
                [10, 11],
                [[-20, -17], [-16, 0], [19, 23], [26, 29]],
            ),
            ([[-22, -1], [17, 26]], [28, 31], [[-22, -1], [17, 26]]),
            ([[-25, -19], [-17, -12], [-3, 12]], [-27, -12], [[-3, 12]]),
            ([[-23, -10], [0, 1], [7, 22]], [-32, -9], [[0, 1], [7, 22]]),
            ([[0, 5], [6, 16]], [-13, 8], [[8, 16]]),
            ([[-8, -4], [5, 9], [22, 30]], [28, 29], [[-8, -4], [5, 9], [22, 28], [29, 30]]),
            (
                [[-30, -25], [-23, -3], [0, 19], [28, 30]],
                [23, 32],
                [[-30, -25], [-23, -3], [0, 19]],
            ),
            ([[17, 22]], [10, 12], [[17, 22]]),
            ([[-24, -11], [7, 15], [17, 20]], [-14, 15], [[-24, -14], [17, 20]]),
            ([[4, 23]], [-17, -12], [[4, 23]]),
            ([[-29, -21], [-4, -1], [7, 24]], [25, 29], [[-29, -21], [-4, -1], [7, 24]]),
        ],
    )
    def test_remove_interval(
        self, intervals: list[list[int]], to_be_removed: list[int], expected: list[list[int]]
    ):
        result = run_remove_interval(Solution, intervals, to_be_removed)
        assert_remove_interval(result, expected)
