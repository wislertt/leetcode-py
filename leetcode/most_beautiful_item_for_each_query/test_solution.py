import pytest

from leetcode_py import logged_test

from .helpers import assert_maximum_beauty, run_maximum_beauty
from .solution import Solution


class TestMostBeautifulItemForEachQuery:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "items, queries, expected",
        [
            ([[1, 2], [3, 2], [2, 4], [5, 6], [3, 5]], [1, 2, 3, 4, 5, 6], [2, 4, 5, 5, 6, 6]),
            ([[1, 2], [1, 2], [1, 3], [1, 4]], [1], [4]),
            ([[10, 1000]], [5], [0]),
            ([[3, 1]], [2, 3, 4], [0, 1, 1]),
            ([[1, 5], [2, 3], [2, 9], [4, 1]], [1, 2, 3, 4], [5, 9, 9, 9]),
            ([[7, 1000]], [7], [1000]),
            ([[5, 1], [5, 2], [5, 3]], [4, 5, 6], [0, 3, 3]),
            ([[1, 1], [1000000000, 1000000000]], [1, 500000000, 1000000000], [1, 1, 1000000000]),
            ([[2, 4], [2, 10], [3, 3]], [2, 3], [10, 10]),
            ([[9, 7]], [8, 9, 10], [0, 7, 7]),
            ([[4, 13], [5, 1], [1, 3]], [1, 2, 3, 4, 5, 6], [3, 3, 3, 13, 13, 13]),
            ([[6, 6], [3, 2], [1, 4]], [1, 2, 3, 6], [4, 4, 4, 6]),
            ([[8, 9], [8, 2]], [7, 8, 9], [0, 9, 9]),
            ([[1, 2], [3, 4], [5, 6]], [1, 4, 7], [2, 4, 6]),
            ([[2, 2], [2, 6], [9, 2], [9, 2]], [13, 2], [6, 6]),
            ([[2, 3]], [9], [3]),
            ([[9, 2], [11, 8], [5, 1], [5, 6]], [5], [6]),
            ([[4, 7], [7, 5], [2, 6], [7, 2]], [6, 13], [7, 7]),
            ([[7, 1], [2, 8], [9, 6], [10, 6], [5, 6], [8, 7]], [8, 12, 6, 9], [8, 8, 8, 8]),
            ([[5, 3], [2, 4], [2, 4], [12, 7], [9, 8], [8, 9]], [14, 10, 14, 7], [9, 9, 9, 4]),
            ([[6, 1], [7, 6]], [12], [6]),
            ([[7, 1]], [13, 15, 13], [1, 1, 1]),
        ],
    )
    def test_maximum_beauty(self, items: list[list[int]], queries: list[int], expected: list[int]):
        result = run_maximum_beauty(Solution, items, queries)
        assert_maximum_beauty(result, expected)
