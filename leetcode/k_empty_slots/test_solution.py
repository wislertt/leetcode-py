import pytest

from leetcode_py import logged_test

from .helpers import assert_k_empty_slots, run_k_empty_slots
from .solution import Solution


class TestKEmptySlots:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "bulbs, k, expected",
        [
            ([1, 3, 2], 1, 2),
            ([1, 2, 3], 1, -1),
            ([1], 0, -1),
            ([2, 1], 0, 2),
            ([1, 2], 0, 2),
            ([3, 1, 2], 1, 2),
            ([2, 3, 1], 1, -1),
            ([1, 4, 2, 3], 2, 2),
            ([4, 1, 3, 2], 2, 2),
            ([6, 1, 4, 2, 5, 3], 2, 3),
            ([1, 6, 3, 5, 2, 4], 1, 3),
            ([5, 2, 4, 1, 3], 0, 3),
            ([2, 5, 3, 1, 4], 3, -1),
            ([3, 1, 2], 0, 3),
            ([2, 3, 1], 2, -1),
            ([2, 1, 3], 3, -1),
            ([4, 1, 3, 2], 0, 3),
            ([1, 3, 2, 4], 1, 2),
            ([2, 3, 1, 4], 2, -1),
            ([1, 4, 3, 2], 3, -1),
            ([3, 4, 1, 2, 5], 0, 2),
            ([1, 3, 4, 2, 5], 1, 2),
            ([2, 3, 4, 1, 5], 2, -1),
            ([4, 1, 3, 2, 5], 3, -1),
            ([1, 3, 5, 2, 6, 4], 0, 4),
            ([2, 6, 4, 3, 5, 1], 1, 3),
            ([2, 3, 6, 1, 4, 5], 2, 3),
            ([2, 6, 4, 1, 3, 5], 3, 2),
            ([1, 3, 2, 5, 6, 7, 4], 0, 3),
            ([5, 3, 6, 4, 2, 7, 1], 1, 2),
            ([4, 3, 6, 2, 1, 7, 5], 2, -1),
            ([7, 6, 5, 1, 3, 4, 2], 3, 4),
            ([5, 4, 7, 9, 10, 1, 8, 3, 2, 6], 0, 2),
            ([5, 3, 1, 8, 10, 7, 2, 6, 4, 9], 2, 4),
            ([3, 7, 8, 6, 2, 1, 5, 9, 10, 4], 5, -1),
            ([2, 11, 3, 5, 8, 12, 9, 1, 7, 4, 10, 6], 0, 3),
            ([5, 1, 4, 11, 3, 9, 7, 8, 10, 6, 2, 12], 2, 3),
            ([10, 8, 6, 2, 11, 4, 12, 9, 7, 3, 1, 5], 5, -1),
            ([1, 4, 10, 3, 12, 9, 7, 15, 5, 11, 13, 2, 6, 8, 14], 0, 4),
            ([13, 11, 1, 9, 12, 6, 5, 14, 15, 2, 7, 8, 3, 10, 4], 2, 6),
            ([4, 7, 1, 3, 6, 11, 8, 13, 10, 2, 5, 14, 12, 15, 9], 5, -1),
        ],
    )
    def test_k_empty_slots(self, bulbs: list[int], k: int, expected: int):
        result = run_k_empty_slots(Solution, bulbs, k)
        assert_k_empty_slots(result, expected)
