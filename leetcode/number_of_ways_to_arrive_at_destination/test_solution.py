import pytest

from leetcode_py import logged_test

from .helpers import assert_count_paths, run_count_paths
from .solution import Solution


class TestNumberOfWaysToArriveAtDestination:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "n, roads, expected",
        [
            (
                7,
                [
                    [0, 6, 7],
                    [0, 1, 2],
                    [1, 2, 3],
                    [1, 3, 3],
                    [6, 3, 3],
                    [3, 5, 1],
                    [6, 5, 1],
                    [2, 5, 1],
                    [0, 4, 5],
                    [4, 6, 2],
                ],
                4,
            ),
            (2, [[1, 0, 10]], 1),
            (1, [], 1),
            (4, [[0, 1, 1], [0, 2, 1], [1, 3, 1], [2, 3, 1]], 2),
            (4, [[0, 1, 1], [1, 2, 1], [2, 3, 1]], 1),
            (4, [[0, 1, 1], [1, 3, 1], [0, 2, 5], [2, 3, 1]], 1),
            (4, [[0, 1, 1], [1, 3, 1], [0, 2, 1], [2, 3, 1], [0, 3, 2]], 3),
            (3, [[0, 1, 1000000000], [1, 2, 1000000000]], 1),
            (5, [[0, 1, 2], [0, 2, 2], [1, 4, 2], [2, 4, 2], [3, 4, 1], [0, 3, 100]], 2),
            (6, [[0, 1, 1], [1, 2, 1], [2, 5, 1], [0, 3, 1], [3, 4, 1], [4, 5, 1]], 2),
            (5, [[0, 1, 1], [1, 2, 1], [2, 4, 1], [1, 3, 1], [3, 4, 1], [0, 3, 2]], 3),
            (5, [[0, 2, 2], [3, 4, 1], [2, 3, 1], [2, 4, 2], [1, 2, 1]], 2),
            (3, [[0, 1, 1], [1, 2, 2], [0, 2, 3]], 2),
            (3, [[1, 2, 1], [0, 2, 3], [0, 1, 2]], 2),
            (5, [[0, 4, 3], [3, 4, 2], [0, 2, 2], [2, 4, 1], [0, 3, 1], [1, 3, 1], [0, 1, 2]], 3),
            (5, [[3, 4, 2], [1, 4, 2], [1, 2, 1], [0, 2, 3], [0, 1, 1], [2, 3, 3], [2, 4, 1]], 2),
            (4, [[1, 2, 2], [2, 3, 1], [1, 3, 3], [0, 1, 2]], 2),
        ],
    )
    def test_count_paths(self, n: int, roads: list[list[int]], expected: int):
        result = run_count_paths(Solution, n, roads)
        assert_count_paths(result, expected)
