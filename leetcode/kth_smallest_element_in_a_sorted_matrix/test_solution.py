import pytest

from leetcode_py import logged_test

from .helpers import assert_kth_smallest, run_kth_smallest
from .solution import Solution


class TestKthSmallestElementInASortedMatrix:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "matrix, k, expected",
        [
            ([[1, 5, 9], [10, 11, 13], [12, 13, 15]], 8, 13),
            ([[-5]], 1, -5),
            ([[1, 2], [1, 3]], 2, 1),
            ([[1, 3, 5], [6, 7, 12], [11, 14, 14]], 9, 14),
            ([[1, 4, 7, 11], [8, 9, 10, 20], [9, 12, 13, 21], [15, 16, 17, 22]], 5, 9),
            ([[-5, -3], [-2, 1]], 2, -3),
            ([[-5, -3], [-2, 1]], 3, -2),
            ([[-2, 1], [-2, 2]], 2, -2),
            ([[-2, 1], [-2, 2]], 4, 2),
            ([[-5, -1], [-2, -1]], 1, -5),
            ([[-5, -1], [-2, -1]], 2, -2),
            ([[-7, -4, -2], [-4, 0, 3], [-3, 1, 7]], 8, 3),
            ([[-7, -4, -2], [-4, 0, 3], [-3, 1, 7]], 9, 7),
            ([[-6, -6, -6], [-4, -3, 1], [-3, 1, 5]], 5, -3),
            ([[-6, -6, -6], [-4, -3, 1], [-3, 1, 5]], 8, 1),
            ([[-6, -6, -6], [-6, -4, -3], [-4, -4, 1]], 3, -6),
            ([[-6, -6, -6], [-6, -4, -3], [-4, -4, 1]], 7, -4),
            ([[0, 3, 3], [3, 3, 3], [3, 3, 3]], 7, 3),
            ([[0, 3, 3], [3, 3, 3], [3, 3, 3]], 9, 3),
            ([[1, 3, 3], [3, 3, 3], [3, 3, 3]], 7, 3),
            ([[1, 3, 3], [3, 3, 3], [3, 3, 3]], 9, 3),
            ([[-2, 1, 1], [2, 3, 3], [3, 3, 3]], 1, -2),
            ([[-2, 1, 1], [2, 3, 3], [3, 3, 3]], 2, 1),
            ([[-10, -8, -8, -4], [-9, -6, -3, -2], [-6, -6, -1, 3], [-5, -3, 2, 5]], 8, -5),
            ([[-10, -8, -8, -4], [-9, -6, -3, -2], [-6, -6, -1, 3], [-5, -3, 2, 5]], 13, -1),
            ([[-10, -10, -8, -6], [-9, -8, -7, -6], [-5, -3, -1, 3], [-1, 0, 3, 7]], 1, -10),
            ([[-10, -10, -8, -6], [-9, -8, -7, -6], [-5, -3, -1, 3], [-1, 0, 3, 7]], 6, -7),
            ([[-8, -4, -1, 3], [-6, 0, 2, 3], [-4, 0, 5, 7], [-4, 0, 6, 11]], 9, 0),
            ([[-8, -4, -1, 3], [-6, 0, 2, 3], [-4, 0, 5, 7], [-4, 0, 6, 11]], 11, 3),
            ([[1, 1], [1, 1]], 3, 1),
            ([[0, 0], [0, 0]], 2, 0),
            ([[-1000000000, -1000000000], [-1000000000, 1000000000]], 3, -1000000000),
            ([[1000000000, 1000000000], [1000000000, 1000000000]], 4, 1000000000),
        ],
    )
    def test_kth_smallest(self, matrix: list[list[int]], k: int, expected: int):
        result = run_kth_smallest(Solution, matrix, k)
        assert_kth_smallest(result, expected)
