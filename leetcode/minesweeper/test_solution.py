import pytest

from leetcode_py import logged_test

from .helpers import assert_update_board, run_update_board
from .solution import Solution


class TestMinesweeper:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "board, click, expected",
        [
            (
                [
                    ["E", "E", "E", "E", "E"],
                    ["E", "E", "M", "E", "E"],
                    ["E", "E", "E", "E", "E"],
                    ["E", "E", "E", "E", "E"],
                ],
                [3, 0],
                [
                    ["B", "1", "E", "1", "B"],
                    ["B", "1", "M", "1", "B"],
                    ["B", "1", "1", "1", "B"],
                    ["B", "B", "B", "B", "B"],
                ],
            ),
            (
                [
                    ["B", "1", "E", "1", "B"],
                    ["B", "1", "M", "1", "B"],
                    ["B", "1", "1", "1", "B"],
                    ["B", "B", "B", "B", "B"],
                ],
                [1, 2],
                [
                    ["B", "1", "E", "1", "B"],
                    ["B", "1", "X", "1", "B"],
                    ["B", "1", "1", "1", "B"],
                    ["B", "B", "B", "B", "B"],
                ],
            ),
            ([["E"]], [0, 0], [["B"]]),
            ([["M"]], [0, 0], [["X"]]),
            ([["E", "M"]], [0, 0], [["1", "M"]]),
            ([["E", "E", "E", "M"]], [0, 1], [["B", "B", "1", "M"]]),
            ([["E", "E"], ["E", "M"]], [0, 0], [["1", "E"], ["E", "M"]]),
            (
                [["E", "E", "E"], ["E", "M", "E"], ["E", "E", "E"]],
                [2, 2],
                [["E", "E", "E"], ["E", "M", "E"], ["E", "E", "1"]],
            ),
            (
                [["E", "E", "E"], ["E", "E", "E"], ["E", "E", "E"]],
                [1, 1],
                [["B", "B", "B"], ["B", "B", "B"], ["B", "B", "B"]],
            ),
            (
                [["E", "E", "M"], ["E", "E", "E"], ["M", "E", "E"]],
                [1, 1],
                [["E", "E", "M"], ["E", "2", "E"], ["M", "E", "E"]],
            ),
            (
                [["M", "M", "M"], ["E", "E", "E"], ["M", "M", "M"]],
                [1, 1],
                [["M", "M", "M"], ["E", "6", "E"], ["M", "M", "M"]],
            ),
            (
                [["E", "E", "E", "E"], ["E", "M", "E", "E"], ["E", "E", "E", "E"]],
                [0, 0],
                [["1", "E", "E", "E"], ["E", "M", "E", "E"], ["E", "E", "E", "E"]],
            ),
            (
                [["E", "E", "E", "E"], ["E", "E", "E", "E"], ["E", "E", "E", "M"]],
                [0, 0],
                [["B", "B", "B", "B"], ["B", "B", "1", "1"], ["B", "B", "1", "M"]],
            ),
            (
                [["M", "E", "E"], ["E", "E", "E"], ["E", "E", "E"]],
                [2, 2],
                [["M", "1", "B"], ["1", "1", "B"], ["B", "B", "B"]],
            ),
            ([["E", "M"], ["E", "E"], ["E", "M"]], [2, 0], [["E", "M"], ["E", "E"], ["1", "M"]]),
            (
                [
                    ["E", "E", "E", "E"],
                    ["E", "M", "M", "E"],
                    ["1", "2", "2", "E"],
                    ["B", "B", "B", "E"],
                ],
                [3, 3],
                [
                    ["E", "E", "E", "E"],
                    ["E", "M", "M", "E"],
                    ["1", "2", "2", "1"],
                    ["B", "B", "B", "B"],
                ],
            ),
            (
                [
                    ["E", "E", "E", "E"],
                    ["E", "M", "M", "E"],
                    ["1", "2", "2", "1"],
                    ["E", "E", "B", "B"],
                ],
                [3, 1],
                [
                    ["E", "E", "E", "E"],
                    ["E", "M", "M", "E"],
                    ["1", "2", "2", "1"],
                    ["B", "B", "B", "B"],
                ],
            ),
            (
                [["B", "B", "E"], ["B", "1", "1"], ["B", "E", "M"]],
                [2, 1],
                [["B", "B", "E"], ["B", "1", "1"], ["B", "1", "M"]],
            ),
            (
                [["E", "B", "B"], ["E", "1", "1"], ["B", "1", "M"]],
                [0, 0],
                [["B", "B", "B"], ["B", "1", "1"], ["B", "1", "M"]],
            ),
            (
                [["E", "M", "E", "E", "E"], ["E", "E", "E", "M", "E"], ["E", "E", "E", "E", "E"]],
                [2, 2],
                [["E", "M", "E", "E", "E"], ["E", "E", "E", "M", "E"], ["E", "E", "1", "E", "E"]],
            ),
        ],
    )
    def test_update_board(
        self, board: list[list[str]], click: list[int], expected: list[list[str]]
    ):
        result = run_update_board(Solution, board, click)
        assert_update_board(result, expected)
