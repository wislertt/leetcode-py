import pytest

from leetcode_py import logged_test

from .helpers import assert_max_alternating_sum, run_max_alternating_sum
from .solution import Solution


class TestMaximumAlternatingSubsequenceSum:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "nums, expected",
        [
            ([4, 2, 5, 3], 7),
            ([5, 6, 7, 8], 8),
            ([6, 2, 1, 2, 4, 5], 10),
            ([1], 1),
            ([100000], 100000),
            ([1, 1], 1),
            ([2, 1], 2),
            ([1, 2], 2),
            ([5, 5, 5, 5], 5),
            ([1, 2, 3, 4, 5], 5),
            ([5, 4, 3, 2, 1], 5),
            ([10, 1, 10, 1, 10], 28),
            ([3, 6, 2, 8, 1, 9], 20),
            ([7, 7, 7, 7, 7, 7, 7], 7),
            ([1, 100000, 1, 100000, 1], 199999),
            ([2, 1, 4, 3, 6, 5, 8, 7], 11),
            ([17, 1, 9, 7, 20, 13], 38),
            ([8, 3], 8),
            ([10, 15, 7], 15),
            ([4, 7, 12, 6, 5], 12),
            ([1], 1),
            ([20, 15, 19, 9, 16], 31),
            ([20], 20),
            ([17, 19, 2, 4, 6, 4, 10, 8, 13], 34),
            ([14], 14),
            ([3, 17, 13, 8, 7, 16, 16, 10], 26),
            ([15, 17, 1, 8, 4, 12, 3, 13, 17], 46),
            ([15, 19], 19),
            ([6, 14, 17, 15], 17),
            ([3, 3, 19, 5, 1, 17, 8, 18, 2], 45),
            ([17, 13, 6, 5, 5, 6, 6, 7, 17], 29),
            ([20, 12, 11, 14], 23),
            ([6, 13, 9, 4, 3, 6, 20, 1, 20, 9], 49),
            ([18, 15, 18, 15, 12, 16], 25),
            ([15, 7, 17, 1, 3, 7, 6, 18, 2], 43),
            ([16, 16, 9, 16, 16, 15, 15, 14], 23),
            ([8, 6, 9, 1, 1, 4, 1, 9, 9, 2, 5, 3, 5], 27),
            ([6, 7, 9, 6, 3, 7, 3, 1, 1, 7, 7, 8, 4], 20),
            ([4, 5, 7, 7, 8, 3, 9, 4, 6, 2, 9, 8], 23),
            ([8, 4, 3, 6, 3, 2, 3, 1, 1, 3, 7, 5, 7], 20),
            ([8, 7, 1, 6, 4, 1, 4, 7, 5, 7, 1, 6], 26),
            ([3, 7, 5, 1, 7, 5, 4, 7, 3, 4, 3, 6, 5], 20),
            ([3, 3, 6, 1, 1, 6, 2, 2, 5, 5, 9], 18),
            ([1, 3, 4, 8, 4, 2, 6, 2, 9, 5, 4, 5], 20),
        ],
    )
    def test_max_alternating_sum(self, nums: list[int], expected: int):
        result = run_max_alternating_sum(Solution, nums)
        assert_max_alternating_sum(result, expected)
