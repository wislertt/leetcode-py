import pytest

from leetcode_py import logged_test

from .helpers import assert_min_available_duration, run_min_available_duration
from .solution import Solution


class TestMeetingScheduler:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "slots1, slots2, duration, expected",
        [
            ([[10, 50], [60, 120], [140, 210]], [[0, 15], [60, 70]], 8, [60, 68]),
            ([[10, 50], [60, 120], [140, 210]], [[0, 15], [60, 70]], 12, []),
            ([[0, 20]], [[5, 25]], 10, [5, 15]),
            ([[1, 10]], [[11, 20]], 5, []),
            ([[5, 100]], [[5, 100]], 95, [5, 100]),
            ([[5, 100]], [[5, 100]], 96, []),
            ([[60, 120], [10, 50]], [[60, 70], [0, 15]], 8, [60, 68]),
            ([[1, 4]], [[2, 5]], 2, [2, 4]),
            ([[1, 2]], [[1, 2]], 1, [1, 2]),
            ([[1, 2], [3, 4], [5, 6]], [[1, 2], [3, 4], [5, 6]], 1, [1, 2]),
            ([[0, 1000000000]], [[999999990, 1000000000]], 10, [999999990, 1000000000]),
            ([[1, 5], [10, 20]], [[5, 10]], 5, []),
            ([[0, 10], [15, 25]], [[5, 20]], 5, [5, 10]),
            ([[0, 10], [15, 25]], [[5, 20]], 11, []),
            ([[0, 10], [20, 30]], [[5, 25]], 10, []),
            ([[0, 4], [10, 30]], [[2, 40]], 8, [10, 18]),
            ([[0, 100]], [[10, 20], [30, 40]], 5, [10, 15]),
            ([[0, 100]], [[10, 20], [30, 40]], 11, []),
            ([[17, 40], [42, 51]], [[5, 11], [17, 21], [27, 40], [41, 56]], 18, []),
            ([[5, 20], [27, 40], [48, 61]], [[3, 22], [29, 42], [43, 60]], 15, [5, 20]),
            ([[17, 18], [19, 24], [36, 39]], [[19, 24], [31, 36]], 1, [19, 20]),
            ([[25, 29]], [[29, 54], [62, 68], [79, 101], [113, 132]], 13, []),
            (
                [[29, 30], [36, 43], [55, 80], [84, 109]],
                [[22, 28], [38, 63], [70, 91]],
                9,
                [70, 79],
            ),
            ([[0, 23], [26, 45]], [[29, 33], [42, 58], [68, 71]], 8, []),
        ],
    )
    def test_min_available_duration(
        self, slots1: list[list[int]], slots2: list[list[int]], duration: int, expected: list[int]
    ):
        result = run_min_available_duration(Solution, slots1, slots2, duration)
        assert_min_available_duration(result, expected)
