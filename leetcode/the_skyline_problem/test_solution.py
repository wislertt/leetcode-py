            ([[0, 2, 3], [2, 5, 3]], [[0, 3], [5, 0]]),
            ([[0, 5, 3]], [[0, 3], [5, 0]]),
            ([[1, 10, 5], [3, 6, 3]], [[1, 5], [10, 0]]),
            ([[0, 4, 3], [0, 6, 5]], [[0, 5], [6, 0]]),
            ([[0, 5, 3], [2, 5, 6]], [[0, 3], [2, 6], [5, 0]]),
            ([[0, 2, 3], [4, 6, 5]], [[0, 3], [2, 0], [4, 5], [6, 0]]),
            ([[0, 3, 4], [3, 6, 4]], [[0, 4], [6, 0]]),
            ([[1, 8, 2], [3, 5, 6]], [[1, 2], [3, 6], [5, 2], [8, 0]]),
            ([[1, 5, 3], [2, 4, 7], [3, 6, 5]], [[1, 3], [2, 7], [4, 5], [6, 0]]),
            ([[0, 5, 7], [0, 3, 5]], [[0, 7], [5, 0]]),
