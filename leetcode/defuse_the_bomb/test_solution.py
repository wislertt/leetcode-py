import pytest

from leetcode_py import logged_test

from .helpers import assert_decrypt, run_decrypt
from .solution import Solution


class TestDefuseTheBomb:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "code, k, expected",
        [
            ([5, 7, 1, 4], 3, [12, 10, 16, 13]),
            ([1, 2, 3, 4], 0, [0, 0, 0, 0]),
            ([2, 4, 9, 3], -2, [12, 5, 6, 13]),
            ([1], 0, [0]),
            ([10], 0, [0]),
            ([4, 5], 1, [5, 4]),
            ([4, 5], -1, [5, 4]),
            ([1, 2, 3], 1, [2, 3, 1]),
            ([1, 2, 3], -1, [3, 1, 2]),
            ([1, 2, 3], 2, [5, 4, 3]),
            ([1, 2, 3], -2, [5, 4, 3]),
            ([5, 5, 5, 5], 2, [10, 10, 10, 10]),
            ([5, 5, 5, 5], -3, [15, 15, 15, 15]),
            ([100, 100, 100, 100, 100, 100], 3, [300, 300, 300, 300, 300, 300]),
            ([1, 2, 3, 4, 5], 0, [0, 0, 0, 0, 0]),
            ([9, 1, 8, 2], 3, [11, 19, 12, 18]),
            ([7, 3, 6, 1, 9], -4, [19, 23, 20, 25, 17]),
            ([2, 2, 2, 2, 2, 2], 5, [10, 10, 10, 10, 10, 10]),
            ([3, 1, 4, 1, 5, 9], 1, [1, 4, 1, 5, 9, 3]),
            ([3, 1, 4, 1, 5, 9], -1, [9, 3, 1, 4, 1, 5]),
            ([24, 42, 88, 53, 52, 46], 0, [0, 0, 0, 0, 0, 0]),
            ([97, 2, 6, 6, 38, 30, 61], -3, [129, 188, 160, 105, 14, 50, 74]),
            ([2, 65, 27, 7, 26, 1, 71], 6, [197, 134, 172, 192, 173, 198, 128]),
            ([90, 72, 38, 34, 74, 5], -1, [5, 90, 72, 38, 34, 74]),
            ([44], 0, [0]),
            (
                [38, 57, 17, 53, 5, 12, 10, 88, 38, 8, 24],
                6,
                [154, 185, 206, 161, 180, 206, 253, 182, 197, 194, 182],
            ),
        ],
    )
    def test_decrypt(self, code: list[int], k: int, expected: list[int]):
        result = run_decrypt(Solution, code, k)
        assert_decrypt(result, expected)
