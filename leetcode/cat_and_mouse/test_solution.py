import pytest

from leetcode_py import logged_test

from .helpers import assert_cat_mouse_game, run_cat_mouse_game
from .solution import Solution


class TestCatAndMouse:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "graph, expected",
        [
            ([[2, 5], [3], [0, 4, 5], [1, 4, 5], [2, 3], [0, 2, 3]], 0),
            ([[1, 3], [0], [3], [0, 2]], 1),
            ([[3], [2], [1, 3], [0, 2]], 2),
            ([[4], [2, 3], [1, 3], [1, 2, 4], [0, 3]], 2),
            ([[1, 2], [0, 2], [0, 1]], 1),
            ([[1, 4], [0, 2], [1, 3], [2, 4], [0, 3]], 1),
            ([[1], [0, 2], [1, 3], [2]], 1),
            ([[2, 5], [4, 7], [0, 5, 6], [7], [1], [0, 2, 7], [2, 7], [1, 3, 5, 6]], 0),
            ([[5], [3, 6], [4, 5], [1, 4, 5], [2, 3], [0, 2, 3], [1]], 0),
            ([[4], [2, 5], [1, 6, 7], [4, 5], [0, 3, 5, 6], [1, 3, 4], [2, 4], [2]], 0),
            ([[7], [2, 4], [1, 6, 7], [4, 5], [1, 3], [3, 6], [2, 5], [0, 2]], 0),
            ([[2, 3], [2, 3, 4], [0, 1], [0, 1, 4], [1, 3]], 1),
            ([[1, 2, 3, 4], [0, 2, 4], [0, 1, 3], [0, 2], [0, 1]], 1),
            ([[1], [0, 2, 3], [1, 3], [1, 2]], 1),
            ([[1, 3, 4], [0, 3], [4, 5], [0, 1], [0, 2, 5], [2, 4]], 1),
            ([[1, 2, 4], [0, 3, 4], [0, 3], [1, 2], [0, 1]], 1),
            ([[1, 4], [0, 2, 5], [1, 3], [2, 4], [0, 3], [1]], 1),
            ([[2, 3, 5], [5], [0, 5], [0, 4, 5], [3, 5], [0, 1, 2, 3, 4]], 2),
            ([[2], [2, 3], [0, 1], [1]], 2),
            ([[2], [2, 4], [0, 1], [4], [1, 3]], 2),
            ([[2, 3, 4], [3], [0, 3, 5], [0, 1, 2, 4, 5], [0, 3, 6], [2, 3, 6], [4, 5]], 2),
            ([[2], [2, 3], [0, 1], [1, 4], [3]], 2),
        ],
    )
    def test_cat_mouse_game(self, graph: list[list[int]], expected: int):
        result = run_cat_mouse_game(Solution, graph)
        assert_cat_mouse_game(result, expected)
