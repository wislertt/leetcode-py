import pytest

from leetcode_py import logged_test

from .helpers import assert_find_rle_array, run_find_rle_array
from .solution import Solution


class TestProductOfTwoRunLengthEncodedArrays:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "encoded1, encoded2, expected",
        [
            ([[1, 3], [2, 3]], [[6, 3], [3, 3]], [[6, 6]]),
            ([[1, 3], [2, 1], [3, 2]], [[2, 3], [3, 3]], [[2, 3], [6, 1], [9, 2]]),
            ([[2, 3]], [[4, 3]], [[8, 3]]),
            ([[5, 1]], [[7, 1]], [[35, 1]]),
            ([[1, 2], [2, 2]], [[3, 2], [2, 2]], [[3, 2], [4, 2]]),
            ([[2, 2], [3, 1]], [[3, 2], [2, 1]], [[6, 3]]),
            ([[1, 1], [2, 2], [1, 1]], [[1, 1], [2, 2], [1, 1]], [[1, 1], [4, 2], [1, 1]]),
            ([[4, 2], [6, 1], [8, 3]], [[2, 4], [3, 2]], [[8, 2], [12, 1], [16, 1], [24, 2]]),
            ([[1, 1], [3, 1], [5, 1]], [[2, 2], [4, 1]], [[2, 1], [6, 1], [20, 1]]),
            ([[10, 2], [20, 2]], [[10, 3], [20, 1]], [[100, 2], [200, 1], [400, 1]]),
            ([[3, 3], [1, 2]], [[1, 2], [3, 3]], [[3, 2], [9, 1], [3, 2]]),
            ([[2, 1], [4, 1], [6, 1]], [[1, 2], [2, 1]], [[2, 1], [4, 1], [12, 1]]),
            ([[7, 1], [14, 2], [21, 1]], [[1, 1], [2, 3]], [[7, 1], [28, 2], [42, 1]]),
            ([[9, 4]], [[1, 1], [3, 3]], [[9, 1], [27, 3]]),
            ([[12, 2], [6, 3]], [[2, 4], [4, 1]], [[24, 2], [12, 2], [24, 1]]),
            ([[1, 4], [2, 4]], [[1, 2], [2, 2], [4, 4]], [[1, 2], [2, 2], [8, 4]]),
            ([[6, 4], [2, 2]], [[3, 4], [5, 1], [6, 1]], [[18, 4], [10, 1], [12, 1]]),
            ([[5, 1], [2, 1]], [[4, 2]], [[20, 1], [8, 1]]),
            ([[6, 1], [2, 1]], [[6, 2]], [[36, 1], [12, 1]]),
            ([[3, 6]], [[3, 4], [4, 1], [6, 1]], [[9, 4], [12, 1], [18, 1]]),
            ([[1, 4], [2, 1]], [[6, 1], [1, 4]], [[6, 1], [1, 3], [2, 1]]),
            ([[4, 6]], [[4, 6]], [[16, 6]]),
            ([[2, 1], [1, 2]], [[2, 1], [3, 1], [6, 1]], [[4, 1], [3, 1], [6, 1]]),
            ([[2, 2]], [[1, 2]], [[2, 2]]),
        ],
    )
    def test_find_rle_array(
        self, encoded1: list[list[int]], encoded2: list[list[int]], expected: list[list[int]]
    ):
        result = run_find_rle_array(Solution, encoded1, encoded2)
        assert_find_rle_array(result, expected)
