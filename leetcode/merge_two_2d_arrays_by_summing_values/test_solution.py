import pytest

from leetcode_py import logged_test

from .helpers import assert_merge_arrays, run_merge_arrays
from .solution import Solution


class TestMergeTwo2dArraysBySummingValues:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "nums1, nums2, expected",
        [
            ([[1, 2], [2, 3], [4, 5]], [[1, 4], [3, 2], [4, 1]], [[1, 6], [2, 3], [3, 2], [4, 6]]),
            ([[2, 4], [3, 6], [5, 5]], [[1, 3], [4, 3]], [[1, 3], [2, 4], [3, 6], [4, 3], [5, 5]]),
            ([[1, 5]], [[1, 3]], [[1, 8]]),
            ([[1, 5]], [[2, 3]], [[1, 5], [2, 3]]),
            ([[1, 1], [2, 2]], [[3, 3], [4, 4]], [[1, 1], [2, 2], [3, 3], [4, 4]]),
            ([[5, 1]], [[1, 2], [3, 4]], [[1, 2], [3, 4], [5, 1]]),
            ([[1, 10], [4, 20]], [[2, 1], [6, 3]], [[1, 10], [2, 1], [4, 20], [6, 3]]),
            ([[1, 1], [2, 1], [3, 1]], [[1, 2], [2, 2], [3, 2]], [[1, 3], [2, 3], [3, 3]]),
            ([[999, 1], [1000, 2]], [[1, 3], [1000, 4]], [[1, 3], [999, 1], [1000, 6]]),
            ([[1, 1000], [2, 1000]], [[2, 1000], [3, 1]], [[1, 1000], [2, 2000], [3, 1]]),
            ([[1, 7]], [[1, 1], [2, 2], [3, 3], [4, 4]], [[1, 8], [2, 2], [3, 3], [4, 4]]),
            ([[1, 1], [2, 2], [3, 3], [4, 4]], [[4, 10]], [[1, 1], [2, 2], [3, 3], [4, 14]]),
            (
                [[2, 5], [11, 3]],
                [[1, 4], [7, 1], [12, 6]],
                [[1, 4], [2, 5], [7, 1], [11, 3], [12, 6]],
            ),
            (
                [[3, 4], [9, 12]],
                [[1, 1], [6, 2], [10, 5]],
                [[1, 1], [3, 4], [6, 2], [9, 12], [10, 5]],
            ),
            ([[9, 8], [38, 3]], [[9, 1], [38, 3]], [[9, 9], [38, 6]]),
            (
                [[3, 9], [20, 3], [34, 7]],
                [[3, 5], [5, 1], [20, 7], [34, 6]],
                [[3, 14], [5, 1], [20, 10], [34, 13]],
            ),
        ],
    )
    def test_merge_arrays(
        self, nums1: list[list[int]], nums2: list[list[int]], expected: list[list[int]]
    ):
        result = run_merge_arrays(Solution, nums1, nums2)
        assert_merge_arrays(result, expected)
