import pytest

from leetcode_py import logged_test

from .helpers import assert_max_number, run_max_number
from .solution import Solution


class TestCreateMaximumNumber:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "nums1, nums2, k, expected",
        [
            ([3, 4, 6, 5], [9, 1, 2, 5, 8, 3], 5, [9, 8, 6, 5, 3]),
            ([6, 7], [6, 0, 4], 5, [6, 7, 6, 0, 4]),
            ([3, 9], [8, 9], 3, [9, 8, 9]),
            ([2, 5, 6, 4, 4, 0], [7, 5, 4, 8, 3, 8, 6], 5, [8, 8, 6, 6, 4]),
            ([5, 5, 1], [4, 0, 1], 3, [5, 5, 4]),
            ([3, 4, 8, 9, 4, 3], [6, 1, 9, 1, 1, 9, 6], 6, [9, 9, 9, 6, 4, 3]),
            ([9, 9, 9], [9], 4, [9, 9, 9, 9]),
            ([1], [1], 1, [1]),
            ([7, 6, 5], [8, 7, 6], 6, [8, 7, 7, 6, 6, 5]),
            ([1, 2, 3, 4, 5], [6, 7, 8, 9], 9, [6, 7, 8, 9, 1, 2, 3, 4, 5]),
            ([9, 1, 2], [1, 2, 9], 4, [9, 9, 1, 2]),
            ([4, 4, 4], [4, 4], 5, [4, 4, 4, 4, 4]),
            ([2, 2, 0], [2, 0, 2], 4, [2, 2, 2, 2]),
            ([8, 9], [3, 4], 4, [8, 9, 3, 4]),
            ([1, 6, 7, 8], [2, 3, 4], 6, [6, 7, 8, 2, 3, 4]),
            ([5, 6, 8], [9, 1], 4, [9, 6, 8, 1]),
            ([3, 5, 8], [8, 5, 3, 9], 4, [9, 3, 5, 8]),
            ([7, 7, 3, 0], [9, 4, 6, 0, 6, 9], 8, [9, 7, 7, 6, 6, 9, 3, 0]),
            ([4, 3], [6], 3, [6, 4, 3]),
            ([9, 5, 1, 4], [8, 5, 3, 8, 6, 3], 9, [9, 8, 5, 8, 6, 5, 3, 1, 4]),
            ([4], [8, 4, 8], 1, [8]),
            ([6, 7, 4], [2, 2, 0, 2, 7, 8], 7, [7, 4, 2, 2, 2, 7, 8]),
            ([6, 4, 2, 8, 0, 1], [9], 3, [9, 8, 1]),
            ([9, 7, 7, 5, 5], [6, 6, 3, 4], 9, [9, 7, 7, 6, 6, 5, 5, 3, 4]),
            ([3, 4, 7, 4], [2], 2, [7, 4]),
            ([4, 9, 2, 8, 9, 2], [9, 9, 5, 0, 9, 9], 5, [9, 9, 9, 9, 9]),
        ],
    )
    def test_max_number(self, nums1: list[int], nums2: list[int], k: int, expected: list[int]):
        result = run_max_number(Solution, nums1, nums2, k)
        assert_max_number(result, expected)
