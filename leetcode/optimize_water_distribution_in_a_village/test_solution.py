import pytest

from leetcode_py import logged_test

from .helpers import assert_min_cost_to_supply_water, run_min_cost_to_supply_water
from .solution import Solution


class TestOptimizeWaterDistributionInAVillage:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "n, wells, pipes, expected",
        [
            (3, [1, 2, 2], [[1, 2, 1], [2, 3, 1]], 3),
            (2, [1, 1], [[1, 2, 1], [1, 2, 2]], 2),
            (2, [5, 7], [[1, 2, 100]], 12),
            (3, [10, 10, 10], [[1, 2, 1], [2, 3, 1], [1, 3, 2]], 12),
            (2, [3, 3], [[1, 2, 0]], 3),
            (2, [0, 5], [[1, 2, 1]], 1),
            (2, [4, 4], [[1, 2, 3], [1, 2, 1], [1, 2, 2]], 5),
            (4, [100, 100, 100, 100], [[1, 2, 1], [2, 3, 1], [3, 4, 1]], 103),
            (4, [1, 50, 1, 50], [[1, 2, 10], [3, 4, 10]], 22),
            (2, [1, 1], [[1, 2, 100]], 2),
            (2, [2, 2], [[1, 2, 2]], 4),
            (
                5,
                [7, 3, 9, 2, 8],
                [[1, 2, 6], [2, 3, 4], [3, 4, 5], [4, 5, 3], [1, 5, 20], [2, 5, 1]],
                16,
            ),
            (
                6,
                [15, 15, 15, 15, 15, 15],
                [[1, 2, 7], [2, 3, 5], [3, 4, 9], [4, 5, 6], [5, 6, 2], [1, 4, 100]],
                44,
            ),
            (6, [9, 1, 8, 11, 9, 10], [[5, 1, 4], [6, 3, 8], [6, 3, 11], [6, 1, 1]], 33),
            (6, [12, 3, 7, 2, 4, 0], [[1, 3, 1], [1, 2, 2], [3, 1, 12]], 12),
            (
                6,
                [10, 12, 8, 3, 1, 1],
                [
                    [2, 4, 3],
                    [4, 5, 11],
                    [4, 3, 2],
                    [6, 1, 8],
                    [3, 4, 6],
                    [4, 6, 5],
                    [4, 1, 8],
                    [1, 6, 1],
                    [3, 2, 12],
                ],
                11,
            ),
            (4, [0, 8, 8, 9], [[3, 4, 4], [3, 2, 3]], 15),
            (
                7,
                [4, 5, 2, 8, 10, 0, 4],
                [
                    [2, 5, 11],
                    [5, 3, 12],
                    [4, 5, 11],
                    [1, 4, 1],
                    [6, 1, 12],
                    [4, 1, 12],
                    [3, 1, 7],
                    [7, 4, 6],
                    [3, 4, 9],
                ],
                26,
            ),
            (
                7,
                [5, 1, 1, 11, 9, 11, 11],
                [[6, 1, 6], [7, 5, 5], [7, 6, 5], [6, 7, 5], [5, 7, 7], [6, 1, 5], [3, 5, 6]],
                33,
            ),
        ],
    )
    def test_min_cost_to_supply_water(
        self, n: int, wells: list[int], pipes: list[list[int]], expected: int
    ):
        result = run_min_cost_to_supply_water(Solution, n, wells, pipes)
        assert_min_cost_to_supply_water(result, expected)
