import pytest

from leetcode_py import logged_test

from .helpers import assert_min_area_free_rect, run_min_area_free_rect
from .solution import Solution


class TestMinimumAreaRectangleII:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "points, expected",
        [
            ([[1, 2], [2, 1], [1, 0], [0, 1]], 2.0),
            ([[0, 1], [2, 1], [1, 1], [1, 0], [2, 0]], 1.0),
            ([[0, 3], [1, 2], [3, 1], [1, 3], [2, 1]], 0.0),
            ([[3, 3]], 0.0),
            ([[0, 0], [5, 5]], 0.0),
            ([[0, 0], [1, 2], [3, 1]], 0.0),
            ([[0, 0], [0, 1], [1, 0], [1, 1]], 1.0),
            ([[1, 2], [2, 3], [3, 2], [2, 1]], 2.0),
            ([[0, 0], [2, 0], [2, 2], [0, 2], [1, 1]], 4.0),
            ([[0, 0], [3, 0], [3, 3], [0, 3], [10, 10], [10, 13], [13, 13], [13, 10]], 9.0),
            ([[0, 0], [1, 1], [2, 2], [3, 3]], 0.0),
            ([[1, 1], [2, 2], [3, 1], [2, 0]], 2.0),
            ([[0, 0], [4, 0], [4, 2], [0, 2], [1, 1], [3, 1]], 8.0),
            ([[0, 0], [1, 2], [3, 2], [2, 0]], 0.0),
            ([[5, 4], [4, 1], [3, 4], [3, 3], [5, 3], [0, 0], [0, 5]], 2.0),
            ([[2, 4], [5, 0], [2, 0], [1, 3], [1, 5], [0, 4]], 2.0),
            ([[2, 1], [4, 5], [1, 5], [1, 1], [1, 2], [2, 2], [0, 5]], 1.0),
            ([[0, 2], [5, 2], [4, 4], [1, 0], [4, 3]], 10.0),
            ([[0, 3], [2, 4], [1, 4], [1, 1], [4, 4], [1, 2], [2, 2]], 2.0),
            ([[1, 1], [1, 3], [0, 0], [4, 5], [2, 0], [5, 5]], 0.0),
            ([[3, 1], [1, 2], [1, 0], [4, 3], [3, 0]], 0.0),
            ([[4, 0], [1, 0], [1, 3], [3, 2], [3, 4], [5, 5]], 0.0),
        ],
    )
    def test_min_area_free_rect(self, points: list[list[int]], expected: float):
        result = run_min_area_free_rect(Solution, points)
        assert_min_area_free_rect(result, expected)
