import pytest

from leetcode_py import logged_test

from .helpers import assert_ip_to_cidr, run_ip_to_cidr
from .solution import Solution


class TestIpToCidr:
    def setup_method(self):
        self.solution = Solution()

    @logged_test
    @pytest.mark.parametrize(
        "ip, n, expected",
        [
            ("255.0.0.7", 10, ["255.0.0.7/32", "255.0.0.8/29", "255.0.0.16/32"]),
            ("117.145.102.62", 8, ["117.145.102.62/31", "117.145.102.64/30", "117.145.102.68/31"]),
            ("1.2.3.4", 1, ["1.2.3.4/32"]),
            ("0.0.0.0", 1024, ["0.0.0.0/22"]),
            ("255.255.255.255", 1, ["255.255.255.255/32"]),
            ("10.0.0.5", 12, ["10.0.0.5/32", "10.0.0.6/31", "10.0.0.8/29", "10.0.0.16/32"]),
            (
                "192.168.1.1",
                100,
                [
                    "192.168.1.1/32",
                    "192.168.1.2/31",
                    "192.168.1.4/30",
                    "192.168.1.8/29",
                    "192.168.1.16/28",
                    "192.168.1.32/27",
                    "192.168.1.64/27",
                    "192.168.1.96/30",
                    "192.168.1.100/32",
                ],
            ),
            ("172.16.0.128", 3, ["172.16.0.128/31", "172.16.0.130/32"]),
            ("8.8.8.8", 16, ["8.8.8.8/29", "8.8.8.16/29"]),
            (
                "254.254.254.200",
                200,
                [
                    "254.254.254.200/29",
                    "254.254.254.208/28",
                    "254.254.254.224/27",
                    "254.254.255.0/25",
                    "254.254.255.128/28",
                ],
            ),
            ("1.0.0.64", 64, ["1.0.0.64/26"]),
            (
                "77.77.77.77",
                55,
                [
                    "77.77.77.77/32",
                    "77.77.77.78/31",
                    "77.77.77.80/28",
                    "77.77.77.96/27",
                    "77.77.77.128/30",
                ],
            ),
            (
                "99.99.99.99",
                999,
                [
                    "99.99.99.99/32",
                    "99.99.99.100/30",
                    "99.99.99.104/29",
                    "99.99.99.112/28",
                    "99.99.99.128/25",
                    "99.99.100.0/23",
                    "99.99.102.0/24",
                    "99.99.103.0/26",
                    "99.99.103.64/29",
                    "99.99.103.72/31",
                ],
            ),
        ],
    )
    def test_ip_to_cidr(self, ip: str, n: int, expected: list[str]):
        result = run_ip_to_cidr(Solution, ip, n)
        assert_ip_to_cidr(result, expected)
